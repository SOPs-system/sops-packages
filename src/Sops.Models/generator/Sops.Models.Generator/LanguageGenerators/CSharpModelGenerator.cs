namespace Sops.Models.Generator.LanguageGenerators;

using System;
using System.Text;

/// <summary>
/// Deterministic code generator for C# domain model contracts.
/// </summary>
public static class CSharpModelGenerator
{
    /// <summary>
    /// Generates C# source code for the specified model definition.
    /// </summary>
    /// <param name="model">The compiled model definition.</param>
    /// <returns>Deterministic C# source code string.</returns>
    public static string GenerateSource(ModelDefinition model)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Deterministically generated by Sops.Models.Generator. Do not modify directly.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine($"namespace Sops.Models.{model.DomainCategory};");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine("using Sops.Models.Common;");
        sb.AppendLine();

        if (!string.IsNullOrWhiteSpace(model.Description))
        {
            sb.AppendLine("/// <summary>");
            sb.AppendLine($"/// {model.Description}");
            sb.AppendLine("/// </summary>");
        }

        if (model.IsEnum)
        {
            sb.AppendLine("[JsonConverter(typeof(JsonStringEnumConverter))]");
            sb.AppendLine($"public enum {model.Title}");
            sb.AppendLine("{");
            for (int i = 0; i < model.EnumValues.Count; i++)
            {
                var ev = model.EnumValues[i];
                var comma = i < model.EnumValues.Count - 1 ? "," : "";
                sb.AppendLine($"    /// <summary>{ev}</summary>");
                sb.AppendLine($"    {ev}{comma}");
            }
            sb.AppendLine("}");
            return sb.ToString();
        }

        sb.AppendLine($"public sealed record {model.Title}");
        sb.AppendLine("{");

        foreach (var p in model.Properties)
        {
            if (!string.IsNullOrWhiteSpace(p.Description))
            {
                sb.AppendLine("    /// <summary>");
                sb.AppendLine($"    /// {p.Description}");
                sb.AppendLine("    /// </summary>");
            }
            sb.AppendLine($"    [JsonPropertyName(\"{p.JsonName}\")]");

            string defaultInit = p.GetCSharpType() switch
            {
                "string" => " = string.Empty;",
                _ when p.IsArray => $" = Array.Empty<{p.ArrayItemType ?? "string"}>();",
                _ => ""
            };

            sb.AppendLine($"    public {p.GetCSharpType()} {p.PascalName} {{ get; init; }}{defaultInit}");
            sb.AppendLine();
        }

        sb.AppendLine("}");
        return sb.ToString();
    }
}
