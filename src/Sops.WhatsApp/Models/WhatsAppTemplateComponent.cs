using System;
using System.Collections.Generic;
using System.Globalization;

namespace Sops.WhatsApp.Models
{
    /// <summary>
    /// Represents a component (header, body, button) within a WhatsApp template message.
    /// </summary>
    public class WhatsAppTemplateComponent
    {
        /// <summary>
        /// Gets or sets the component type (e.g. "header", "body", "button").
        /// </summary>
        public string Type { get; set; } = "body";

        /// <summary>
        /// Gets or sets the button sub-type (e.g. "url", "quick_reply", "copy_code") when <see cref="Type"/> is "button".
        /// </summary>
        public string? SubType { get; set; }

        /// <summary>
        /// Gets or sets the zero-based button index as a string when <see cref="Type"/> is "button".
        /// </summary>
        public string? Index { get; set; }

        /// <summary>
        /// Gets or sets the parameters injected into the component.
        /// </summary>
        public List<WhatsAppTemplateParameter> Parameters { get; set; } = new List<WhatsAppTemplateParameter>();

        /// <summary>
        /// Creates a header template component with parameters.
        /// </summary>
        /// <param name="parameters">The header parameters.</param>
        /// <returns>A new <see cref="WhatsAppTemplateComponent"/>.</returns>
        public static WhatsAppTemplateComponent CreateHeader(params WhatsAppTemplateParameter[] parameters)
        {
            var component = new WhatsAppTemplateComponent { Type = "header" };
            if (parameters != null)
            {
                component.Parameters.AddRange(parameters);
            }
            return component;
        }

        /// <summary>
        /// Creates a body template component with parameters.
        /// </summary>
        /// <param name="parameters">The body parameters.</param>
        /// <returns>A new <see cref="WhatsAppTemplateComponent"/>.</returns>
        public static WhatsAppTemplateComponent CreateBody(params WhatsAppTemplateParameter[] parameters)
        {
            var component = new WhatsAppTemplateComponent { Type = "body" };
            if (parameters != null)
            {
                component.Parameters.AddRange(parameters);
            }
            return component;
        }

        /// <summary>
        /// Creates a body template component with plain text substitution parameters.
        /// </summary>
        /// <param name="textParameters">The text strings to substitute into placeholders {{1}}, {{2}}, etc.</param>
        /// <returns>A new <see cref="WhatsAppTemplateComponent"/>.</returns>
        public static WhatsAppTemplateComponent CreateBodyWithText(params string[] textParameters)
        {
            var component = new WhatsAppTemplateComponent { Type = "body" };
            if (textParameters != null)
            {
                foreach (string text in textParameters)
                {
                    component.Parameters.Add(WhatsAppTemplateParameter.CreateText(text));
                }
            }
            return component;
        }

        /// <summary>
        /// Creates a button template component.
        /// </summary>
        /// <param name="subType">The button subtype ("url", "quick_reply", "copy_code").</param>
        /// <param name="index">The zero-based button index.</param>
        /// <param name="parameters">Parameters for the button.</param>
        /// <returns>A new <see cref="WhatsAppTemplateComponent"/>.</returns>
        public static WhatsAppTemplateComponent CreateButton(string subType, int index, params WhatsAppTemplateParameter[] parameters)
        {
            if (string.IsNullOrWhiteSpace(subType))
            {
                throw new ArgumentException("Button subType cannot be null or whitespace.", nameof(subType));
            }

            var component = new WhatsAppTemplateComponent
            {
                Type = "button",
                SubType = subType,
                Index = index.ToString(CultureInfo.InvariantCulture)
            };

            if (parameters != null)
            {
                component.Parameters.AddRange(parameters);
            }

            return component;
        }

        /// <summary>
        /// Creates a body component for an authentication / OTP template delivering the OTP code.
        /// Note: The caller is responsible for generating the OTP code securely.
        /// </summary>
        /// <param name="otpCode">The one-time password code generated by the caller.</param>
        /// <returns>A new <see cref="WhatsAppTemplateComponent"/>.</returns>
        public static WhatsAppTemplateComponent CreateOtpBody(string otpCode)
        {
            if (string.IsNullOrWhiteSpace(otpCode))
            {
                throw new ArgumentException("OTP code cannot be null or whitespace.", nameof(otpCode));
            }

            return CreateBody(WhatsAppTemplateParameter.CreateText(otpCode));
        }

        /// <summary>
        /// Creates a button component for an authentication / OTP template with a dynamic URL or copy code button.
        /// </summary>
        /// <param name="index">The zero-based index of the button.</param>
        /// <param name="otpCode">The one-time password code generated by the caller.</param>
        /// <returns>A new <see cref="WhatsAppTemplateComponent"/>.</returns>
        public static WhatsAppTemplateComponent CreateOtpButton(int index, string otpCode)
        {
            if (string.IsNullOrWhiteSpace(otpCode))
            {
                throw new ArgumentException("OTP code cannot be null or whitespace.", nameof(otpCode));
            }

            return CreateButton("url", index, WhatsAppTemplateParameter.CreateText(otpCode));
        }
    }
}
